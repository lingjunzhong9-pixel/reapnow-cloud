    @Override
    public void run(String... args) {
        if (demandRepository.count() > 0) {
            return;
        }
        LocalDate today = LocalDate.now();
        int i = 0;
        for (String[] row : DATA) {
            seed(row[0], row[1], row[2], row[3], row[4],
                    row[5], row[6], CropStage.valueOf(row[7]),
                    today.plusDays(Long.parseLong(row[8])),
                    "1".equals(row[9]), row[10], i++);
        }
        System.out.println("[demand-service] 种子需求已写入 " + demandRepository.count() + " 条（跨 8 个地区）");
    }

    private void seed(String username, String farmerName, String farmerPhone, String plotName,
                      String region, String mu, String price, CropStage stage,
                      LocalDate deadline, boolean lodged, String remark, int seq) {
        Long farmerId;
        try {
            UserVO u = userClient.byUsername(username).getData();
            farmerId = (u == null ? 1L : u.id());
        } catch (Exception e) {
            farmerId = 1L;
        }
        Demand d = new Demand();
        d.setDemandNo("DM" + System.currentTimeMillis() + String.format("%03d", seq + 1));
        d.setFarmerId(farmerId);
        d.setFarmerName(farmerName);
        d.setFarmerPhone(farmerPhone);
        d.setPlotName(plotName);
        d.setRegion(region);
        d.setMu(new BigDecimal(mu));
        d.setRemainMu(new BigDecimal(mu));
        d.setPricePerMu(new BigDecimal(price));
        d.setCropStage(stage);
        d.setDeadline(deadline);
        d.setLodged(lodged);
        d.setRemark(remark);
        d.setStatus(DemandStatus.OPEN);
        d.setCreatedAt(LocalDateTime.now().minusHours(seq));
        demandRepository.save(d);
    }
